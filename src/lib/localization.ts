export function localizeTextWithFallback(locale: "ko" | "en", ko: string, en: string) {
  if (locale !== "ko") {
    return en;
  }

  const translated = localizeText("ko", en);
  if (translated !== en) {
    return translated;
  }

  if (isLikelyValidKorean(ko)) {
    return ko;
  }

  return en;
}
