export function localizeLiveQuoteUnavailableNote(
  locale: "ko" | "en",
  reason?: string | null,
  quoteTitle?: string | null
) {
  const raw = String(reason ?? "").trim();
  const title = String(quoteTitle ?? "").trim();
  const resolvedTitle =
    title || (locale === "ko" ? "선택한 비교 시세" : "the selected comparison quote");

  const httpMatch = raw.match(/^HTTP\s+(\d+)\s+from\s+/i);
  if (httpMatch) {
    const statusCode = httpMatch[1];
    return locale === "ko"
      ? `실시간 시세를 불러오지 못했습니다. 소스가 HTTP ${statusCode} 응답을 반환했습니다.`
      : `Live quote unavailable. The source returned HTTP ${statusCode}.`;
  }

  const chartErrorMatch = raw.match(/^([A-Z0-9_]+):\s+(.+)$/);
  if (chartErrorMatch) {
    const code = chartErrorMatch[1];
    return locale === "ko"
      ? `실시간 시세를 불러오지 못했습니다. 차트 피드 오류 코드 ${code}가 반환됐습니다.`
      : `Live quote unavailable. The chart feed returned error code ${code}.`;
  }

  const noChartMatch = raw.match(/^No chart result returned for\s+(.+)\.$/i);
  if (noChartMatch) {
    const symbol = noChartMatch[1];
    return locale === "ko"
      ? `실시간 시세를 불러오지 못했습니다. ${symbol} 차트 결과가 비어 있습니다.`
      : `Live quote unavailable. No chart result was returned for ${symbol}.`;
  }

  if (/^No live quote could be resolved for\s+/i.test(raw)) {
    return locale === "ko"
      ? `실시간 시세를 불러오지 못했습니다. ${resolvedTitle}에 대한 유효한 피드를 찾지 못했습니다.`
      : `Live quote unavailable. No valid feed could be resolved for ${resolvedTitle}.`;
  }

  return locale === "ko"
    ? "실시간 시세를 불러오지 못했습니다. 소스 응답을 다시 확인해야 합니다."
    : `Live quote unavailable: ${raw}`;
}

